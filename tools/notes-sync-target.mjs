import { lstat, realpath, readFile, readdir, rm, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const MARKER = '<!-- Generated by scripts/sync-obsidian-notes.mjs from Obsidian Publish. Do not edit by hand. -->';
const MANIFEST = '.obsidian-notes-sync-manifest.json';
const slash = value => value.replaceAll('\\', '/');
const relative = file => slash(path.relative(process.cwd(), file));
const inside = (file, root) => { const r = path.relative(root, file); return r === '' || (!r.startsWith('..') && !path.isAbsolute(r)); };
const fail = message => { throw new Error(`Target sync ownership/manifest: ${message}`); };

function exactRelative(value) {
  if (typeof value !== 'string') fail('target must be an exact relative path');
  const normalized = slash(value);
  if (!normalized || normalized.startsWith('/') || /^[A-Za-z]:/.test(normalized) || normalized.includes(':') || normalized.includes('\0') || normalized.split('/').some(p => !p || p === '.' || p === '..')) fail('target must be an exact relative path without traversal');
  return normalized;
}

export async function selectSyncTarget({ source, target, records, skipReason }) {
  const name = exactRelative(target);
  if (!/\.mdx?$/i.test(name)) fail('target must name a Markdown file');
  const parts = name.split('/');
  if (parts.some((part, i) => part.startsWith('.') || skipReason(part, i < parts.length - 1))) fail('target is not publication eligible');
  const file = path.resolve(source, name);
  const resolved = await realpath(file).catch(() => fail('target does not exist'));
  if (!inside(resolved, await realpath(source))) fail('target symlink escapes source');
  const record = records.find(r => r.relativePath === name);
  if (!record || record.frontmatter.draft === true) fail('target does not exist or is not publication eligible');
  return record;
}

async function safePath(file, root) {
  if (!inside(file, root) || file === root) fail('output path escapes its directory');
  // Reject symlinked output ancestors as well as symlinked leaf files.
  let current = path.resolve(process.cwd());
  for (const part of path.relative(current, file).split(path.sep)) {
    current = path.join(current, part);
    const s = await lstat(current).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
    if (s?.isSymbolicLink()) fail('symlinked output path');
  }
}

async function generated(file) {
  const raw = await readFile(file, 'utf8').catch(error => { if (error.code === 'ENOENT') return null; throw error; });
  if (raw === null) return false;
  const normalized = raw.replace(/^\uFEFF/, '');
  const frontmatter = normalized.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n/);
  if (!frontmatter) fail('generated output requires frontmatter before marker');
  const body = normalized.slice(frontmatter[0].length);
  if (!body.startsWith(MARKER + '\n') && !body.startsWith(MARKER + '\r\n')) fail('refusing unmarked hand-written output');
  return true;
}

async function hasExistingGenerated(root) {
  const entries = await readdir(root, { withFileTypes: true }).catch(error => { if (error.code === 'ENOENT') return []; throw error; });
  for (const e of entries) {
    if (e.isSymbolicLink()) fail('cannot infer ownership through symlink');
    const file = path.join(root, e.name);
    if (e.isDirectory() && await hasExistingGenerated(file)) return true;
    if (e.isFile() && /\.mdx?$/i.test(e.name) && (await readFile(file,'utf8')).includes(MARKER)) return true;
  }
  return false;
}

function validateManifest(m, outDir, assetsDir) {
  if (!m || typeof m !== 'object' || Array.isArray(m) || !['notes','noteRecords','assets'].every(k => Array.isArray(m[k]))) fail('invalid manifest shape');
  const outputs = new Set(), sources = new Set(), slugs = new Set();
  for (const record of m.noteRecords) {
    if (!record || typeof record !== 'object' || typeof record.slug !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(record.slug)) fail('invalid manifest record');
    const source = exactRelative(record.sourcePath);
    const expected = relative(path.join(outDir, record.slug + '.md'));
    if (source !== record.sourcePath || record.output !== expected || outputs.has(record.output) || sources.has(source) || slugs.has(record.slug)) fail('ambiguous manifest record ownership');
    outputs.add(record.output); sources.add(source); slugs.add(record.slug);
  }
  if (m.notes.length !== outputs.size || new Set(m.notes).size !== m.notes.length || m.notes.some(n => !outputs.has(n))) fail('manifest notes do not match records');
  if (new Set(m.assets).size !== m.assets.length) fail('duplicate manifest assets');
  for (const asset of m.assets) {
    const clean = exactRelative(asset);
    const file = path.resolve(asset);
    const parts = slash(path.relative(assetsDir, file)).split('/');
    if (clean !== asset || !inside(file, assetsDir) || parts.length < 2 || !slugs.has(parts[0])) fail('asset is outside manifest slug ownership');
  }
}

function mergeOwnedEntries(entries, { owns, replacement, compare }) {
  const canonical = entries.every((entry, index) => index === 0 || compare(entries[index - 1], entry) <= 0);
  const next = [];
  let placed = false;
  for (const entry of entries) {
    if (!owns(entry)) next.push(entry);
    else if (!placed) { next.push(...replacement); placed = true; }
  }
  if (!placed) next.push(...replacement);
  return canonical ? next.sort(compare) : next;
}

const comparePaths = (a, b) => a === b ? 0 : a < b ? -1 : 1;

export async function planTargetSync({ item, assetPlan, outDir, assetsDir }) {
  const manifestPath = path.join(assetsDir, MANIFEST);
  await safePath(manifestPath, assetsDir);
  const raw = await readFile(manifestPath, 'utf8').catch(error => { if (error.code === 'ENOENT') return null; throw error; });
  let m;
  if (raw === null) {
    const assetEntries = await readdir(assetsDir).catch(error => { if (error.code === 'ENOENT') return []; throw error; });
    if (await hasExistingGenerated(outDir) || assetEntries.length) fail('manifest absent with existing generated outputs/assets');
    m = { assets: [], noteRecords: [], notes: [] };
  } else {
    try { m = JSON.parse(raw); } catch { fail('corrupt manifest JSON'); }
  }
  validateManifest(m, outDir, assetsDir);
  const old = m.noteRecords.find(r => r.sourcePath === item.record.relativePath);
  const output = relative(item.outFile);
  const nextOwner = m.noteRecords.find(r => r.output === output);
  if (nextOwner && nextOwner !== old) fail('destination belongs to another source');
  await safePath(item.outFile, outDir);
  if (old) {
    await safePath(path.resolve(old.output), outDir);
    if (!await generated(path.resolve(old.output))) fail('previous manifest output is missing');
  }
  if (await lstat(item.outFile).catch(error => { if (error.code === 'ENOENT') return null; throw error; })) {
    if (!old || output !== old.output) fail('destination exists without target manifest ownership');
    await generated(item.outFile);
  }
  const prefix = old ? relative(path.join(assetsDir, old.slug)) + '/' : null;
  const oldAssets = m.assets.filter(a => prefix && a.startsWith(prefix));
  const nextAssets = [...new Set(assetPlan.map(a => relative(a.destination)))].sort();
  const newPrefix = relative(path.join(assetsDir, item.record.slug)) + '/';
  for (const plan of assetPlan) {
    const destination = relative(plan.destination);
    if (!destination.startsWith(newPrefix)) fail('new asset outside target slug');
    await safePath(plan.destination, assetsDir);
    const existing = await lstat(plan.destination).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
    if (existing && !oldAssets.includes(destination)) fail('asset destination is not owned by target');
  }
  const removeFiles = oldAssets.filter(a => !nextAssets.includes(a)).map(a => path.resolve(a));
  if (old && old.output !== output) removeFiles.push(path.resolve(old.output));
  for (const file of removeFiles) await safePath(file, file === path.resolve(old?.output ?? '') ? outDir : assetsDir);
  const record = { ...old, output, slug: item.record.slug, sourcePath: item.frontmatter.sourcePath,
    collection: item.frontmatter.collection, modulePath: item.frontmatter.modulePath, module: item.frontmatter.module,
    isIndex: item.frontmatter.isIndex, noteRole: item.frontmatter.noteRole };
  if (record.sourcePath !== item.record.relativePath) fail('converted source identity does not match target');
  const next = { ...m,
    assets: mergeOwnedEntries(m.assets, { owns: a => oldAssets.includes(a),
      replacement: [...oldAssets.filter(a => nextAssets.includes(a)), ...nextAssets.filter(a => !oldAssets.includes(a))], compare: comparePaths }),
    noteRecords: mergeOwnedEntries(m.noteRecords, { owns: r => r === old, replacement: [record], compare: (a,b) => a.output.localeCompare(b.output) }),
    notes: mergeOwnedEntries(m.notes, { owns: n => n === old?.output, replacement: [output], compare: comparePaths }),
  };
  validateManifest(next, outDir, assetsDir);
  const unchanged = ['assets','noteRecords','notes'].every(k => JSON.stringify(m[k]) === JSON.stringify(next[k]));
  const content = raw !== null && unchanged ? raw : JSON.stringify({ ...next, generatedAt: new Date().toISOString() },null,2) + '\n';
  return { manifestPath, content, unchanged: content === raw, removeFiles };
}

export async function applyTargetCleanup(plan, { dryRun, actions }) {
  for (const file of plan.removeFiles) {
    actions.push(`${dryRun ? 'would remove' : 'removed'} ${relative(file)}`);
    if (!dryRun) await rm(file, { force: true });
  }
}

export async function writeTargetManifest(plan, { dryRun, actions }) {
  actions.push(`${plan.unchanged ? 'unchanged' : dryRun ? 'would write' : 'wrote'} ${relative(plan.manifestPath)}`);
  if (!dryRun && !plan.unchanged) {
    await mkdir(path.dirname(plan.manifestPath), { recursive: true });
    await writeFile(plan.manifestPath, plan.content, 'utf8');
  }
}
